//! Glyph names and simple-font encodings, for turning text-showing
//! operators back into Unicode.
//!
//! The glyph list is the part of the Adobe Glyph List that fonts in
//! circulation actually use (Latin, punctuation, symbols, Greek, Cyrillic
//! basics); `uniXXXX` and `uXXXX` names are decoded arithmetically.

/// Unicode for a glyph name, if known.
pub fn glyph_to_char(name: &str) -> Option<char> {
    if let Some(hex) = name.strip_prefix("uni") {
        if hex.len() >= 4 {
            if let Ok(v) = u32::from_str_radix(&hex[..4], 16) {
                return char::from_u32(v);
            }
        }
    }
    if let Some(hex) = name.strip_prefix('u') {
        if (4..=6).contains(&hex.len()) && hex.chars().all(|c| c.is_ascii_hexdigit()) {
            if let Ok(v) = u32::from_str_radix(hex, 16) {
                return char::from_u32(v);
            }
        }
    }
    // Names like "a.sc", "one.oldstyle": use the base name.
    let base = name.split('.').next().unwrap_or(name);
    if base.len() == 1 {
        return base.chars().next();
    }
    AGL.iter().find(|(n, _)| *n == base).map(|(_, c)| *c)
}

