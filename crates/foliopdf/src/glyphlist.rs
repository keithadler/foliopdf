#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names() {
        assert_eq!(glyph_to_char("eacute"), Some('é'));
        assert_eq!(glyph_to_char("uni20AC"), Some('€'));
        assert_eq!(glyph_to_char("u1F600"), Some('😀'));
        assert_eq!(glyph_to_char("a.sc"), Some('a'));
        assert_eq!(glyph_to_char("fi"), Some('ﬁ'));
        assert_eq!(glyph_to_char("g123"), None);
    }

    #[test]
    fn encodings() {
        assert_eq!(standard_encoding(0x27), Some('’'));
        assert_eq!(winansi_encoding(0x92), Some('’'));
        assert_eq!(macroman_encoding(0x8E), Some('é'));
        assert_eq!(symbol_encoding(0x61), Some('α'));
    }
}
